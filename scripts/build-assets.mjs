// Build-time asset pipeline (Node is only needed during development, not on the server):
//  • self-hosted fonts      → public/assets/fonts
//  • Quill rich-text editor → public/assets/vendor/quill
//  • Lucide icon map        → app/data/lucide.php  (icons are rendered as inline SVG by PHP)
//  • Tailwind CSS           → public/assets/css/tailwind.css (minified)
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const nm = join(root, 'node_modules');
const require = createRequire(import.meta.url);
const copy = (from, to) => { mkdirSync(dirname(join(root, to)), { recursive: true }); copyFileSync(join(nm, from), join(root, to)); };

// Fonts
for (const w of [400, 500, 600, 700]) copy(`@fontsource/barlow/files/barlow-latin-${w}-normal.woff2`, `public/assets/fonts/barlow-latin-${w}-normal.woff2`);
for (const w of [500, 600, 700]) copy(`@fontsource/barlow-condensed/files/barlow-condensed-latin-${w}-normal.woff2`, `public/assets/fonts/barlow-condensed-latin-${w}-normal.woff2`);
for (const w of [600, 700]) copy(`@fontsource/playfair-display/files/playfair-display-latin-${w}-normal.woff2`, `public/assets/fonts/playfair-display-latin-${w}-normal.woff2`); // optional editorial headings

// Quill
copy('quill/dist/quill.js', 'public/assets/vendor/quill/quill.js');
copy('quill/dist/quill.snow.css', 'public/assets/vendor/quill/quill.snow.css');
copy('qrcode-generator/qrcode.js', 'public/assets/vendor/qrcode/qrcode.js'); // QR codes for authenticator-app setup

// Lucide → PHP array of inner SVG markup
const { icons } = require('lucide');
const kebab = (n) => n.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([a-zA-Z])(\d)/g, '$1-$2').toLowerCase();
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
const phpStr = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const entries = Object.entries(icons).map(([name, [, , children]]) => {
  const inner = children.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).map(([k, v]) => `${k}="${esc(v)}"`).join(' ')}/>`).join('');
  return `${phpStr(kebab(name))}=>${phpStr(inner)}`;
});
mkdirSync(join(root, 'app/data'), { recursive: true });
writeFileSync(join(root, 'app/data/lucide.php'), `<?php\n// Generated by scripts/build-assets.mjs from lucide@${require('lucide/package.json').version} (ISC licence). Do not edit.\nreturn [${entries.join(',\n')}];\n`);

// Minified CSS + JS (sources in resources/, output in public/assets/) via esbuild
const esbuild = await import('esbuild');
const codeTargets = [
  { in: 'resources/css/style.css', out: 'public/assets/css/style.css', loader: 'css' },
  { in: 'resources/css/admin.css', out: 'public/assets/css/admin.css', loader: 'css' },
  { in: 'resources/js/main.js', out: 'public/assets/js/main.js', loader: 'js' },
  { in: 'resources/js/admin.js', out: 'public/assets/js/admin.js', loader: 'js' },
  { in: 'resources/js/passkey.js', out: 'public/assets/js/passkey.js', loader: 'js' },
  { in: 'resources/js/pwtoggle.js', out: 'public/assets/js/pwtoggle.js', loader: 'js' },
];
const buildOpts = (t) => ({
  entryPoints: [join(root, t.in)], outfile: join(root, t.out), bundle: false, minify: true,
  target: t.loader === 'js' ? ['es2020'] : ['chrome90', 'firefox88', 'safari14'], legalComments: 'none', logLevel: 'warning',
});
if (process.argv.includes('--watch-code')) {
  for (const t of codeTargets) await (await esbuild.context(buildOpts(t))).watch();
  console.log('Watching resources/css and resources/js for changes…');
  await new Promise(() => {}); // keep running
}
for (const t of codeTargets) await esbuild.build(buildOpts(t));

// Tailwind
const watch = process.argv.includes('--watch');
const res = spawnSync(`npx tailwindcss -c tailwind.config.js -i resources/tailwind.css -o public/assets/css/tailwind.css ${watch ? '--watch' : '--minify'}`, { cwd: root, shell: true, stdio: 'inherit' });
if (res.status !== 0) process.exit(res.status ?? 1);
console.log(`Assets built: fonts, Quill, ${entries.length} icons, minified CSS/JS (${codeTargets.length} files), Tailwind CSS.`);
